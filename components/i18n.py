LANGUAGE_NAMES = {"en": "English", "ru": "Русский"}
LANGUAGE_STATE_KEY = "app_language"
LANGUAGE_WIDGET_KEY = "language_selector_widget"


def translate(key: str, language: str = "en", **values) -> str:
    """Translate a key, falling back to English and then to the key itself."""
    english = EN.get(key, key)
    localized = RU.get(key, english) if language == "ru" else english
    return localized.format(**values) if values else localized


def t(key: str, **values) -> str:
    """Translate using the current session language (English by default)."""
    language = st.session_state.get(LANGUAGE_STATE_KEY, "en")
    return translate(key, language, **values)


def _save_selected_language() -> None:
    """Persist the selector choice outside its page-scoped widget state."""
    st.session_state[LANGUAGE_STATE_KEY] = st.session_state[LANGUAGE_WIDGET_KEY]


def render_language_selector() -> str:
    """Render the shared sidebar selector without touching application data."""
    if st.session_state.get(LANGUAGE_STATE_KEY) not in LANGUAGE_NAMES:
        st.session_state[LANGUAGE_STATE_KEY] = "en"
    if (
        st.session_state.get(LANGUAGE_WIDGET_KEY)
        != st.session_state[LANGUAGE_STATE_KEY]
    ):
        st.session_state[LANGUAGE_WIDGET_KEY] = st.session_state[LANGUAGE_STATE_KEY]
    st.sidebar.selectbox(
        t("common.language"),
        options=tuple(LANGUAGE_NAMES),
        key=LANGUAGE_WIDGET_KEY,
        format_func=lambda language: LANGUAGE_NAMES[language],
        on_change=_save_selected_language,
    )
    return st.session_state[LANGUAGE_STATE_KEY]
